"""40 independent autoregressive steps from a verified update-38 checkpoint.

Reuses the weekly input, official model, rollout and output-metric conventions.
Native precision routing is copied unchanged from the training experiment so
updated weights are rounded afresh, without the original-weight lookup table.
"""
import argparse
import ctypes as C
import dataclasses
import datetime
import hashlib
import importlib.metadata as md
import os
import pickle
import time
from pathlib import Path

import haiku as hk
import jax
import numpy as np
import xarray as xr
from graphcast import autoregressive, checkpoint, graphcast, normalization, rollout, xarray_jax
from graphcast_bench.assets import ROOT, STATS, code_snapshot, load_case, read_json, sha256, verify_source, write_json
from graphcast_bench.metrics import final_frame, validate_case_grid_units
from precision import Precision


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--mode', choices=['fp32', 'rne_xf32'], required=True)
    parser.add_argument('--checkpoint-mode', choices=['fp32', 'rne_xf32'])
    args = parser.parse_args()
    training_mode = args.checkpoint_mode or args.mode
    out, data = Path('/output'), Path('/data')
    case, prepared = load_case(data)
    upstream, code = verify_source(), code_snapshot()
    experiment = {p.name: sha256(p) for p in Path('/experiment').iterdir() if p.is_file()}
    assert Path(graphcast.__file__).resolve().is_relative_to(ROOT / 'third_party/graphcast')
    assert md.version('jax') == '0.6.0+das.opt1.dtk2604'
    assert not jax.config.jax_enable_x64 and os.environ.get('ROCBLAS_MATH_MODE') is None
    devices = jax.devices('gpu')
    assert len(devices) == 1 and 'BW1200' in devices[0].device_kind
    hip = C.CDLL('libamdhip64.so')
    bus = C.create_string_buffer(64)
    assert hip.hipDeviceGetPCIBusId(bus, 64, 0) == 0
    assert bus.value.decode().lower() == os.environ['EXPECTED_PCI']

    with (data / 'assets/jax_weights.npz').open('rb') as f:
        original = checkpoint.load(f, graphcast.CheckPoint)
    folder = Path('/training') / (training_mode + '-r12')
    training = read_json(folder / 'report.json')
    checkpoint_sha = sha256(folder / 'checkpoint.pkl')
    assert checkpoint_sha == training['checkpoint_sha256']
    assert training['status'] == 'completed' and training['mode'] == training_mode
    assert training['rows'][-1]['update'] == 38 and not training['tiny']
    # Trusted local artifact generated by this experiment; not an external pickle.
    with (folder / 'checkpoint.pkl').open('rb') as f:
        saved = pickle.load(f)
    assert saved['updates'] == 38 and saved['mode'] == training_mode and not saved['tiny']
    assert saved['data_sha256'] == training['data_sha256']
    params_host = saved['params']
    del saved
    leaves, tree = jax.tree_util.tree_flatten(params_host)
    old_leaves, old_tree = jax.tree_util.tree_flatten(original.params)
    assert tree == old_tree
    assert all(x.dtype == np.float32 and x.shape == y.shape and np.isfinite(x).all()
               for x, y in zip(leaves, old_leaves))
    params_sha = hashlib.sha256(b''.join(np.asarray(x).tobytes() for x in leaves)).hexdigest()
    assert params_sha == training['final_params_sha256']
    assert dataclasses.asdict(original.model_config) == training['model']
    assert json_normalize(dataclasses.asdict(original.task_config)) == training['task']

    inputs, forcings, target = [xr.load_dataset(data / 'assets' / name, decode_timedelta=True)
        for name in ('inputs.nc', 'rollout_forcings.nc', 'target_template.nc')]
    stats = {name.removesuffix('.nc'): xr.load_dataset(data / 'assets/stats' / name).astype(np.float32)
             for name in STATS}
    targets = rollout.extend_targets_template(target.drop_vars('datetime', errors='ignore'), 40)
    targets = targets.assign_coords(datetime=forcings.datetime)
    assert case['steps'] == 40 and case['lead_hours'] == 240
    control = Precision()
    report = dict(schema='graphcast.trained_checkpoint_inference40.v1', status='running',
        mode=args.mode, training_mode=training_mode, training_updates=38, checkpoint=str(folder / 'checkpoint.pkl'),
        checkpoint_sha256=checkpoint_sha, params_sha256=params_sha,
        training_report_sha256=sha256(folder / 'report.json'),
        source=upstream, code_sha256=code, experiment_sha256=experiment, data=prepared,
        case=case, model=training['model'], task=training['task'],
        device=dict(index=int(os.environ['PHYSICAL_DEVICE']), pci=bus.value.decode(),
                    driver_name=devices[0].device_kind, user_name='BW1100'),
        versions={n: md.version(n) for n in ('jax', 'jaxlib', 'dm-haiku', 'optax', 'numpy', 'xarray')},
        precision='FP32 arrays. Native SGEMM: FP32, or fresh RNE of both operands + XF32.',
        jax_matmul_precision='highest', xla_flags=os.environ['XLA_FLAGS'],
        warmup_steps=5, measured_steps=40, repeats=1,
        autoregression='Reset to fixed initial input after warmup; feed back own predictions for all 40 steps.',
        timing='Host synchronized predictor/wall times for run audit only; not GPU-only performance measurements.',
        started_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(), rows=[])
    write_json(out / 'report.json', report)

    @hk.transform_with_state
    def predict(inputs, targets_template, forcings):
        model = graphcast.GraphCast(original.model_config, original.task_config)
        model = normalization.InputsAndResiduals(model, **stats)
        model = autoregressive.Predictor(model, gradient_checkpointing=False)
        return model(inputs, targets_template=targets_template, forcings=forcings)

    with jax.default_device(devices[0]), jax.default_matmul_precision('highest'):
        params = jax.device_put(params_host)
        apply = jax.jit(lambda rng, inputs, targets_template, forcings:
            predict.apply(params, {}, rng, inputs, targets_template, forcings)[0])

        def execute(label, steps):
            times, audits = [], []
            first_kwargs = None

            def call(**kwargs):
                nonlocal first_kwargs
                if first_kwargs is None:
                    first_kwargs = kwargs
                step = len(times) + 1
                control.select(args.mode, '%s-step-%02d' % (label, step))
                before = control.counts()
                start = time.perf_counter()
                result = apply(**kwargs)
                jax.block_until_ready(result)
                seconds = time.perf_counter() - start
                counts = control.delta(before)
                assert counts['calls'] >= 84
                if label == 'rollout' or step > 1:
                    assert counts['calls'] == 84, counts
                assert counts['rounded'] == (counts['calls'] if args.mode == 'rne_xf32' else 0)
                times.append(seconds)
                audits.append(dict(label=label, step=step, seconds=seconds, **counts))
                print(args.mode, label, step, 'seconds', round(seconds, 4), 'GEMM', counts, flush=True)
                return result

            assert hip.hipDeviceSynchronize() == 0
            start = time.perf_counter()
            last = None
            # Each call creates a new generator with the original input; warmup
            # state cannot enter the measured forecast. No teacher forcing.
            for chunk in rollout.chunked_prediction_generator(
                predictor_fn=call, rng=jax.random.PRNGKey(0), inputs=inputs,
                targets_template=targets.isel(time=slice(0, steps)),
                forcings=forcings.isel(time=slice(0, steps)), num_steps_per_chunk=1):
                last = chunk
            jax.block_until_ready(last)
            assert last is not None and len(times) == steps
            return last, dict(label=label, steps=steps, apply_seconds=times,
                apply_sum_seconds=sum(times), wall_seconds=time.perf_counter()-start, audit=audits), first_kwargs

        print('LOAD VERIFIED; START WARMUP', args.mode, checkpoint_sha, flush=True)
        _, warmup, kwargs = execute('warmup', 5)
        report['warmup'] = warmup
        (out / 'optimized-hlo.txt').write_text(apply.lower(**kwargs).compile().as_text())
        cache = apply._cache_size()
        write_json(out / 'report.json', report)
        last, row, _ = execute('rollout', 40)
        assert apply._cache_size() == cache
        row.update(jit_cache_before=cache, jit_cache_after=apply._cache_size())
        host = xr.Dataset({k: (v.dims, np.asarray(jax.device_get(xarray_jax.unwrap_data(v))), target[k].attrs)
                           for k, v in last.data_vars.items()}, coords=last.coords)
        assert set(host.data_vars) == set(training['task']['target_variables'])
        final_frame(host, case['initialization_time'], case['lead_hours'])
        validate_case_grid_units(host, case)
        host.to_netcdf(out / 'prediction.nc')
        row['output_sha256'] = sha256(out / 'prediction.nc')
        row['output_variables'] = sorted(host.data_vars)
        report['rows'].append(row)
    assert sha256(folder / 'checkpoint.pkl') == checkpoint_sha
    load_case(data)
    assert code_snapshot() == code
    assert {p.name: sha256(p) for p in Path('/experiment').iterdir() if p.is_file()} == experiment
    report.update(status='completed', completed_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                  optimized_hlo_sha256=sha256(out / 'optimized-hlo.txt'))
    write_json(out / 'report.json', report)
    print('COMPLETED', args.mode, '40 steps; finite final +240h output saved.', flush=True)


def json_normalize(value):
    import json
    return json.loads(json.dumps(value))


if __name__ == '__main__':
    main()
